# Turns the Blender renders into what chiketi serves: WebP files (alpha kept for the parts)
# in chiketi/assets/tubes/, manifest.json (every file, its size, the layout hash and one hash
# over them all), and the generated chiketi/assets/ui/tubes_layout.js the renderer reads.
# Usage: python3 tools/tube-renders/pack.py <render dir>
import hashlib
import io
import json
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import layout  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
ASSETS = os.path.join(REPO, 'chiketi', 'assets', 'tubes')
LAYOUT_JS = os.path.join(REPO, 'chiketi', 'assets', 'ui', 'tubes_layout.js')
# The parts the renderer uses (the v4 IN-14 'nixie' part is not one of them).
PARTS = (['jewel-%s-%s' % (c, s) for c in ('amber', 'blue', 'green', 'red', 'white') for s in ('on', 'off')] +
         ['ann-%s' % c for c in ('amber', 'blue', 'green', 'off', 'red', 'white')] +
         ['eye-back', 'eye-front', 'in12-back', 'in12-front', 'in13-back', 'in13-front', 'tabplate'])
PANELS = ['panel-%s-%d' % (v, h) for v in layout.VARIANTS for h in layout.HEIGHTS]


def webp(src):
    im = Image.open(src)
    im = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB')
    out = io.BytesIO()
    im.save(out, 'WEBP', quality=86, method=6)
    return im.size, out.getvalue()


def compact_layout():
    """What the renderer needs: labels and slots (plates and paint are baked)."""
    out = {}
    for v in layout.VARIANTS:
        out[v] = {}
        for h in layout.HEIGHTS:
            s = layout.screen(v, h)
            out[v][str(h)] = {'labels': s['labels'], 'slots': s['slots']}
    return out


def main(src):
    os.makedirs(ASSETS, exist_ok=True)
    files, digest = {}, hashlib.sha256(layout.layout_hash().encode())
    for name in PANELS + PARTS:
        path = os.path.join(src, name + '.png')
        if not os.path.exists(path):
            sys.exit('missing render: ' + path)
        (w, h), data = webp(path)
        with open(os.path.join(ASSETS, name + '.webp'), 'wb') as f:
            f.write(data)
        files[name] = {'w': w, 'h': h, 'bytes': len(data)}
        digest.update(name.encode() + hashlib.sha256(data).digest())
    # Where the glow goes in each tube, as the Blender scripts measured it.
    meta = {}
    with open(os.path.join(src, 'meta.json')) as f:
        meta['in13'] = json.load(f)['in13']          # tubes.py
    with open(os.path.join(src, 'in12.json')) as f:
        meta['in12'] = json.load(f)                  # in12.py
    manifest = {'hash': digest.hexdigest()[:12], 'layout_hash': layout.layout_hash(), 'files': files, 'meta': meta}
    info = os.path.join(src, 'render-info.json')
    if os.path.exists(info):
        with open(info) as f:
            manifest['rendered_with'] = json.load(f)
    with open(os.path.join(ASSETS, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=1, sort_keys=True)
    js = ('/* ── tubes_layout.js: generated by tools/tube-renders/pack.py from layout.py and the renders; do not edit.\n'
          '   TUBES_LAYOUT[variant][height] holds the label plates and slots the renderer fills;\n'
          '   TUBES_HASH versions the image URLs; TUBES_FILES lists every servable part. */\n'
          'const TUBES_HEIGHTS = %s;\nconst TUBES_HASH = %s;\nconst TUBES_LAYOUT_HASH = %s;\n'
          'const TUBES_FILES = %s;\nconst TUBES_META = %s;\nconst TUBES_LAYOUT = %s;\n') % (
        json.dumps(layout.HEIGHTS), json.dumps(manifest['hash']), json.dumps(manifest['layout_hash']),
        json.dumps(sorted(files)), json.dumps(manifest['meta'], sort_keys=True),
        json.dumps(compact_layout(), sort_keys=True, separators=(',', ':')))
    with open(LAYOUT_JS, 'w') as f:
        f.write(js)
    total = sum(x['bytes'] for x in files.values())
    print('packed %d files, %.2f MB, hash %s' % (len(files), total / 1048576, manifest['hash']))


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, 'build', 'tube-renders'))
